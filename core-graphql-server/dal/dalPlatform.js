  function validateExportRequestDateTimeFilter(dateTimeFilter) {
    if (!dateTimeFilter) return;

    const { fromDateTime, toDateTime } = dateTimeFilter;
    if (!fromDateTime || !toDateTime) {
      throw new InvalidInput({
        message: 'fromDateTime and toDateTime are required fields.'
      });
    }

    if (
      !moment(new Date(fromDateTime)).isValid() ||
      !moment(new Date(toDateTime)).isValid()
    ) {
      throw new InvalidInput({
        message: 'fromDateTime and toDateTime must be valid date strings.'
      });
    }

    if (moment(new Date(toDateTime)).isBefore(new Date(fromDateTime))) {
      throw new InvalidInput({
        message: 'fromDateTime must occur before toDateTime.'
      });
    }

    if (
      !canExportLogsOlderThan12Months &&
      moment(new Date(toDateTime)).diff(
        moment(new Date(fromDateTime)),
        'months',
        true
      ) > 12
    ) {
      throw new InvalidInput({
        message: 'Time range filter must not exceed 12 months.'
      });
    }
  }

