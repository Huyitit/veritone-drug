  // helper function to format incoming export request timestamps to unix
  function roundToSecond(dateTime) {
    const date = new Date(dateTime);
    date.setMilliseconds(0);

    return date.toISOString();
  }

  // helper function to compare incoming export request with existing requests within the same organization
  function compareAuditLogExportRequest(newRequest, existingRequests) {
    let existingRequestId;
    // format incoming filter's date string to match db's unix timestamp
    const formattedRequest = {
      ...newRequest,
      dateTimeFilter: {
        fromDateTime: roundToSecond(newRequest.dateTimeFilter.fromDateTime),
        toDateTime: roundToSecond(newRequest.dateTimeFilter.toDateTime)
      }
    };
    for (const request of existingRequests) {
      if (_.isEqual(request.filters, formattedRequest)) {
        existingRequestId = request.id;
        break;
      }
    }
    if (existingRequestId) {
      throw new Error(
        `An export request with the same filters already exists. Request ID: ${existingRequestId}`
      );
    }
  }

  async function createAuditLogExportRequest(ctx, args = {}) {
    const isSuperAdmin = resUtil.isSuperAdmin(ctx._authInfo);
    const clientInfo = resUtil.getClientInfo(ctx);
    try {
      // validate input
      const dateTimeFilter = _.get(args, 'dateTimeFilter');
      validateExportRequestDateTimeFilter(dateTimeFilter);

      const organizationId = _.get(args, 'organizationId');
      if (organizationId) {
        await validateExportRequestOrgAccess(ctx, organizationId, clientInfo.org);
      } else {
        // if no organizationId is provided, use the requestor's organization
        args.organizationId = clientInfo.org;
      }

      // check if the same request already exists
      const { records } = await getAuditLogExportRequestObjectsForOrg(
        ctx,
        {
          organizationId: args.organizationId,
          statuses: ['PENDING', 'IN_PROGRESS']
        },
        false,
        true,
        true
      );
      const resolvedRecords = await Promise.all(records);
      if (resolvedRecords.length > 0) {
        throw new Error(
          `An export request for this organization already exists and it is in ${resolvedRecords[0].status} status. 
        Request ID: ${resolvedRecords[0].id}. Please wait for the current request to complete or cancel it before creating a new one.`
        );
      }

      const mailboxOrgId = isSuperAdmin
        ? organizationId || clientInfo.org
        : clientInfo.org;
      const options = {
        userId: clientInfo.id,
        name: _.get(
          serviceContext,
          'config.mailbox.reservedNames.exportStatusMailbox'
        ),
        organizationId: mailboxOrgId
      };

      const mailbox = await serviceContext.bll.mailbox.createMailboxIfNotExists(
        ctx,
        options,
        true
      );

      // persist the request if no duplicate exists after comparison
      const requestObjects = await persistAuditLogExportRequest(
        ctx,
        args,
        clientInfo.id,
        mailbox.id
      );

      return formatAuditLogExportRequestResponse(requestObjects[0]);
    } catch (err) {
      const payloadPublicEvent = {        
        requestorId: clientInfo.id,
        createdDateTime: new Date().toISOString(),
        filters: args
      };
      emitExportRequestPublicEvent(
        ctx,
        payloadPublicEvent,
        eventsMap.AuditLogExportCreate,
        err,
        'Failed to create an audit log export'
      );
      throw err;
    } 
  }

