  function _getAIWAREVersionHistorySql(args) {
    let { limit, offset, versions, ids } = args || {};

    const sqlArgs = [];
    const conditions = [];
    // Filter by version ids
    let _ids = [];
    if (!_.isNil(ids)) {
      if (_.isArray(ids)) {
        _ids = ids;
      } else {
        _ids.push(ids);
      }
      sqlArgs.push(_ids);
      conditions.push(` v.id = ANY($${sqlArgs.length}::uuid[])`);
    }
    // Filter by version
    let _versions = [];
    if (!_.isNil(versions)) {
      if (_.isArray(versions)) {
        _versions = versions;
      } else {
        _versions.push(versions);
      }
      sqlArgs.push(_versions);
      conditions.push(` v.version = ANY($${sqlArgs.length}::varchar[])`);
    }

    const versionSelectClause = mainUtil.makeSelectClause(
      aiWAREVersionColumns,
      'v'
    );
    // add the history
    let sql = `SELECT
                 ${versionSelectClause},
                  h.history_id,
                  h.installed_by,
                  h.installed_at,
                  h.created_at history_created_at
                FROM
                  ${aiWAREVersionTableName} v
                INNER JOIN ${aiWAREVersionHistoryTableName} h ON h.version_id = v.id
                ${
                  conditions.length === 0
                    ? ''
                    : ` WHERE ${conditions.join(' AND ')}`
                }
                ORDER BY h.installed_at DESC`;

    // Pagination
    if (!Number.isInteger(limit)) {
      limit = 30;
    }
    if (!Number.isInteger(offset)) {
      offset = 0;
    }

    sqlArgs.push(limit);
    sql += ` LIMIT \$${sqlArgs.length}`;

    sqlArgs.push(offset);
    sql += ` OFFSET \$${sqlArgs.length}`;

    return {
      sql,
      sqlArgs,
      pageArgs: { limit, offset }
    };
  }

