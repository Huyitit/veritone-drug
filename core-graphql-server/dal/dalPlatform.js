  /**
   * This function takes a valid version and compares it
   * to the 'current' version (if one exists) in the aiware_version table.
   * In order to service existence of an input version,
   * the function also returns a boolean values to make that determination.
   * @param {Object} context The request context
   * @param {Object} args contain input with organizationId
   * @returns {Object}
   *  tipVersion: The most recenently submitted version number.
   *  currentVersion: A string belonging to the 'current' version (aka installed version)
   *  isExisting: The input version number was found in the aiware_version table.
   *    This does not provide any other information about its existence.
   *  createdAt: If the version is existing, the createdAt date is returned. This is to
   *    provide information when adding a version, but the version already exists and
   *    needs the required field to return.
   *
   */
  async function getVersionCompatability(version) {
    let comparison = {
      tipVersion: '',
      currentVersion: '',
      isExisting: false
    };

    const sql = `
      (
        (SELECT
          -- Tip most Version (highest version number, but may or may not be the currently installed version)
          version tip_version,
          -- Currently installed version
          (SELECT version FROM ${aiWAREVersionTableName} WHERE installed_at = (SELECT MAX(installed_at) FROM ${aiWAREVersionTableName})) current_version,
          -- Does the input version exist?
          (SELECT COUNT(*) FROM ${aiWAREVersionTableName} WHERE version = $1) is_existing
        FROM 
          ${aiWAREVersionTableName}
        ORDER BY 
          created_at DESC
        LIMIT 1)
        
        UNION ALL

        (SELECT NULL tip_version, NULL current_version, 0 is_existing) -- default SELECT when table is empty
      )
      LIMIT 1; -- return only 1 row for the UNION
    `;

    try {
      comparison = await dbRead.one(sql, [version], mapper.camelizeRootKeys);

      // convert bools
      comparison.isExisting = comparison.isExisting === '1';
    } catch (err) {
      throw new Error('Unable to make a valid version comparison.');
    }

    return comparison;
  }

  async function getVersion(context, version) {
    let ver;

    if (!version) {
      throw new InvalidInput({
        message: 'The version is a required field.'
      });
    }

    try {
      const rows = await getVersions(context, { version });
      ver = _.head(rows);
    } catch (err) {
      // throw handled below
    }

    if (!ver) {
      throw new Error(
        `Unable to retrieve platform version information for ${version}.`
      );
    }

    return ver;
  }

  async function getVersions(context, args) {
    const where = [];
    const values = [];

    if (args.version) {
      mainUtil.addSqlWhere('version', args.version, where, values);
    }

    const selectColumns = mainUtil.makeSelectClause(aiWAREVersionColumns);
    let sql = `
      SELECT 
        ${selectColumns} 
      FROM 
        ${aiWAREVersionTableName}`;

    if (where.length > 0) {
      sql += `\n WHERE ${where.join(' AND ')}`;
    }

    const orderBy =
      aiWAREVersionOrderByMap[args.orderBy] ||
      aiWAREVersionOrderByMap.createdAt;
    const orderDir =
      orderDirectionMap[args.orderDirection] || orderDirectionMap.desc;

    sql += `\n ORDER BY ${orderBy} ${orderDir}`;

    if (orderBy === aiWAREVersionOrderByMap.installedAt) {
      sql += ` NULLS LAST`;
    }

    if (Number.isInteger(args.limit)) {
      values.push(args.limit);
      sql += `\n LIMIT \$${values.length}`;
    }

    if (Number.isInteger(args.offset)) {
      values.push(args.offset);
      sql += `\n OFFSET \$${values.length}`;
    }

    try {
      return await dbRead.map(sql, values, mapper.camelizeRootKeys);
    } catch (err) {
      logger.error('Unable to retrieve the platform versions.', err);
      throw new Error('Unable to retrieve the platform versions.');
    }
  }

