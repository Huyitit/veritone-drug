  function reverseStatusLookup(value) {
    const entry = Object.entries(auditLogExportRequestStatus).find(
      ([key, val]) => val === value
    );
    return entry ? entry[0] : new Error('Invalid status value');
  }

  async function formatAuditLogExportRequestResponse(exportReq) {
    const { status, filters = {}, downloadUrl } = exportReq;

    let formattedDateTimeFilter;
    const dateTimeFilter = filters.dateTimeFilter;
    if (dateTimeFilter) {
      formattedDateTimeFilter = {
        fromDateTime: moment(
          _.get(dateTimeFilter, 'fromDateTime')
        ).toISOString(),
        toDateTime: moment(_.get(dateTimeFilter, 'toDateTime')).toISOString()
      };
    }

    let signedDownloadUrl = downloadUrl;
    if (downloadUrl) {
      signedDownloadUrl = await serviceContext.storage.getSignedUrlPromise(
        downloadUrl
      );
    }

    return {
      ...exportReq,
      filters: {
        ...filters,
        dateTimeFilter: formattedDateTimeFilter
          ? formattedDateTimeFilter
          : undefined
      },
      status: auditLogExportRequestStatus[status],
      downloadUrl: signedDownloadUrl
    };
  }

  /**
   * This function adds a platform version to the aiware_version table.
   * This only establishes a version, but it does not set it as the
   * currently installed version. Use the setCurrentPlatform version
   * to set the state to installed (aka 'current').
   * @param {Object} context The request context
   * @param {Object} args contain input with organizationId
   * @returns {Object} Returns a single object of all fields including
   * the id, which may have already been generated by the calling client
   * or within the dal.
   */
  async function addPlatformVersion(context, args) {
    const { input } = args;
    let version = input.version;
    const { userInfo, tokenInfo } = context.requestContext;
    const assemblePayload = (version, createdPlatformVersion, err) => ({
      serviceName: SERVICE_NAME,
      id: uuidv4(),
      version,
      versionId: _.get(createdPlatformVersion, 'id'),
      createdBy: _.get(createdPlatformVersion, 'createdBy'),
      // actionInfo
      actionInfo: messageUtil.buildActionInfo(
        _.get(createdPlatformVersion, 'id'),
        err,
        'create',
        !err ? 'success' : 'failure',
        !err
          ? `Created platform version ${version}`
          : 'Failed to create new platform version'
      )
    });
    const emitNewPlatformVersionAvailableEvent = async (
      version,
      createdPlatformVersion,
      err
    ) => {
      const event = assemblePayload(version, createdPlatformVersion, err);
      serviceContext.messageUtil.emitPublicEvent(
        supportedEvents.NewVersionAvailable,
        SYSTEM_APPLICATION_ID,
        context,
        event
      );
    };
    const emitNewVersionAuditEvent = async (
      version,
      createdPlatformVersion,
      err
    ) => {
      const event = assemblePayload(version, createdPlatformVersion, err);
      serviceContext.messageUtil.emitPublicEvent(
        supportedEvents.PlatformNewVersionAvailable,
        SYSTEM_APPLICATION_ID,
        context,
        event
      );
    };
    try {
      if (_.isNil(input)) {
        throw new InvalidInput({
          message: `The required input object was not found.`
        });
      }

      let userId = _.get(userInfo, 'userId') || _.get(tokenInfo, 'userId');
      if (_.isNil(userId)) {
        // If user info could not be gathered from the token, then assume this
        // is a user-less API token
        userId = 'aiWareInstanceAdmin';
      }

      if (input.id && !validator.isUUID(input.id)) {
        throw new InvalidInput({
          message: `Invalid ID format '${input.id}'. ID must be in the UUID format.`
        });
      }

      if (!version) {
        throw new InvalidInput({
          message: 'The version is a required field.'
        });
      }

      if (!input.manifestUrl) {
        input.manifestUrl = '';
      }

      if (!input.changeLogUrl) {
        input.changeLogUrl = '';
      }

      if (!input.highlightsUrl) {
        input.highlightsUrl = '';
      }

      // if id not supplied, generate one
      let id = input.id;
      if (!id) {
        id = uuidv4();
      }

      let columnData = {
        id: id,
        version: version,
        manifestUrl: input.manifestUrl,
        changeLogUrl: input.changeLogUrl,
        highlightsUrl: input.highlightsUrl,
        originalManifestUrl: input.manifestUrl,
        originalChangeLogUrl: input.changeLogUrl,
        originalHighlightsUrl: input.highlightsUrl,
        createdBy: userId
      };

      let createdPlatformVersion = columnData;
      const { isExisting } = await getVersionCompatability(version);
      if (!isExisting) {
        columnData = mapper.decamelizeRootKeys(columnData);

        const { sql, values } = mainUtil.makeInsertSql(
          aiWAREVersionTableName,
          columnData,
          aiWAREVersionColumns
        );

        try {
          createdPlatformVersion = await dbWrite.one(
            sql,
            values,
            mapper.camelizeRootKeys
          );
        } catch (err) {
          throw new Error('Unable to add a new platform version entry.');
        }
        emitNewPlatformVersionAvailableEvent(version, createdPlatformVersion);
      } else {
        //The version already exists. Return that existing version information.
        createdPlatformVersion = await getVersion(context, version);
      }
      emitNewVersionAuditEvent(version, createdPlatformVersion);
      return createdPlatformVersion;
    } catch (err) {
      emitNewVersionAuditEvent(version, null, err);
      throw err;
    }
  }

  /**
   * This function takes a valid version that is located in the
   * aiware_version table and stamps the installed_by and installed_at
   * fields. While having MAX(installed_at) date makes the version,
   * the 'current' version.
   * @param {Object} context The request context
   * @param {Object} args contain input with organizationId
   * @returns {Object} Returns a single object of all aiware_version fields.
   */
  async function setCurrentPlatformVersion(context, args) {
    const { version } = args;
    const { userInfo, tokenInfo } = context.requestContext;
    const assemblePayload = (currentPlatformVersion, err) => ({
      serviceName: SERVICE_NAME,
      id: uuidv4(),
      version,
      versionId: _.get(currentPlatformVersion, 'id'),
      installedAt: moment(
        _.get(currentPlatformVersion, 'installedAt')
      ).toISOString(),
      installedBy: _.get(currentPlatformVersion, 'installedBy'),
      createdBy: _.get(currentPlatformVersion, 'createdBy'),
      // actionInfo
      actionInfo: messageUtil.buildActionInfo(
        _.get(currentPlatformVersion, 'id'),
        err,
        'update',
        !err ? 'success' : 'failure',
        !err
          ? `Installed platform version ${version}`
          : `Failed to install platform version ${version}`
      )
    });

    const emitNewPlatformVersionInstalledEvent = async (
      currentPlatformVersion,
      err
    ) => {
      const event = assemblePayload(currentPlatformVersion, err);
      serviceContext.messageUtil.emitPublicEvent(
        supportedEvents.NewVersionInstalled,
        SYSTEM_APPLICATION_ID,
        context,
        event
      );
    };

    const emitVersionInstalledAuditEvent = async (
      currentPlatformVersion,
      err
    ) => {
      const event = assemblePayload(currentPlatformVersion, err);
      serviceContext.messageUtil.emitPublicEvent(
        supportedEvents.PlatformNewVersionInstalled,
        SYSTEM_APPLICATION_ID,
        context,
        event
      );
    };
    let userId = _.get(userInfo, 'userId') || _.get(tokenInfo, 'userId');
    if (_.isNil(userId)) {
      // If user info could not be gathered from the token, then assume this
      // is a user-less API token
      userId = 'aiWareInstanceAdmin';
    }

    try {
      let validVersion = version;
      if (!validVersion) {
        throw new InvalidInput({
          message: 'The version is a required field.'
        });
      }

      // The version must exist
      const { isExisting, currentVersion } = await getVersionCompatability(
        version
      );

      let currentPlatformVersion;
      if (currentVersion !== version) {
        if (!isExisting) {
          throw new Error(
            `The input version, '${validVersion}' does not exist`
          );
        }

        const values = [userId, version];

        const returningData = mainUtil.makeSelectClause(aiWAREVersionColumns);

        const sql = `-- set the version to installed
                    UPDATE
                        ${aiWAREVersionTableName}
                    SET
                      installed_at = NOW(),
                      installed_by = $1
                    WHERE
                      version = $2;
  
                    -- add to version history
                    INSERT INTO
                      ${aiWAREVersionHistoryTableName}(
                        version_id,
                        installed_at,
                        installed_by
                      )
                      SELECT
                        id,
                        installed_at,
                        installed_by
                      FROM
                        ${aiWAREVersionTableName}
                      WHERE
                        version = $2;
                      
                    -- return this data
                    SELECT
                      ${returningData}
                    FROM
                      ${aiWAREVersionTableName}
                    WHERE 
                      version = $2;`;

        context.tx = dbWrite;
        try {
          currentPlatformVersion = await dbWrite.one(
            sql,
            values,
            mapper.camelizeRootKeys
          );
        } catch (err) {
          throw new Error('Unable to set the current version.');
        }
      } else {
        // The current version is already set. Return the current version.
        currentPlatformVersion = await getVersion(context, version);
      }
      emitNewPlatformVersionInstalledEvent(currentPlatformVersion);
      emitVersionInstalledAuditEvent(currentPlatformVersion);
      return currentPlatformVersion;
    } catch (err) {
      emitNewPlatformVersionInstalledEvent(null, err);
      emitVersionInstalledAuditEvent(null, err);
      throw err;
    }
  }

