  async function updateInstanceAuditLogConfig(_ctx, args, info) {
    const { userInfo, tokenInfo } = _ctx.requestContext;

    let userId = _.get(userInfo, 'userId') || _.get(tokenInfo, 'userId');
    const event = {
      serviceName: SERVICE_NAME,
      id: uuidv4(),
      updatedBy: userId,
      updatedAt: new Date().toISOString()
    };

    const emitEvent = (status, err = null) => {      
      let defaultMessage = !err ? `Updated the audit log configuration` : `Failed to update the audit log configuration`;            
      const payload = {
        ...event,
        actionInfo: messageUtil.buildActionInfo(
          null,
          err,
          eventsMap.AuditLogConfigChange.action,
          status,
          defaultMessage
        )
      };
      serviceContext.messageUtil.emitPublicEvent(
        eventsMap.AuditLogConfigChange.name,
        SYSTEM_APPLICATION_ID,
        _ctx,
        payload
      );
    };

    const { addAuditEvents = [], removeAuditEvents = [] } = args;
    if (_.intersection(addAuditEvents, removeAuditEvents).length > 0) {
      emitEvent(
        'failure',
        { statusCode: 400 },
        'Cannot add and remove the same event in the same request'
      );
      throw new InvalidInput({
        message: 'Cannot add and remove the same event in the same request.'
      });
    }
    const unsupportedEvents = [];
    function filterEvents(ev) {
      if (!eventsMap[ev]) {
        emitEvent(
          'failure',
          { statusCode: 400 },
          `Event ${ev} is not found in the events map`
        );
        logger.error(
          `Event ${ev} is not found in the events map`
        );
        unsupportedEvents.push(ev);
        return null;
      } else {
        return ev;
      }
    }

    const eventsToRemove = removeAuditEvents
      .filter(filterEvents)
      .map((ev) => eventsMap[ev].event);

    const eventsToAdd = addAuditEvents
      .filter(filterEvents)
      .map((ev) => eventsMap[ev].event);
    if (unsupportedEvents.length > 0) {
      emitEvent(
        'failure',
        { statusCode: 400 },
        `One or more events are not supported for audit logging`
      );
      throw new InvalidInput({
        message: `One or more events are not supported for audit logging: ${unsupportedEvents.join(
          ', '
        )}. Please remove them from the request and try again.`
      });
    }
    if (eventsToAdd.length === 0 && eventsToRemove.length === 0) {
      emitEvent(
        'failure',
        { statusCode: 400 },
        `None of the provided events is not supported for audit logging`
      );
      throw new InvalidInput({
        message: `None of the provided events is not supported for audit logging: ${[
          ...addAuditEvents,
          removeAuditEvents
        ].join(', ')}`
      });
    }

    let sql = `
        WITH updated_events AS (
          SELECT ARRAY(
              SELECT DISTINCT event
              FROM unnest(audit_config.configured_events || $2::text[]) AS event
              WHERE event NOT IN (SELECT unnest($1::text[]))
              AND NOT event = ANY(audit_config.baseline_events)
          ) AS updated_configured_events
          FROM aiware.audit_config
        )
        UPDATE aiware.audit_config
        SET configured_events = updated_events.updated_configured_events
        FROM updated_events
        RETURNING baseline_events, configured_events;`;
    const auditConfig = await dbWrite.one(
      sql,
      [eventsToRemove, eventsToAdd],
      mapper.camelizeRootKeys
    );
    const { baselineEvents = [], configuredEvents = [] } = auditConfig;
    emitEvent('success');
    const schemaEventNames = _.get(
      info,
      'schema._typeMap.EventNameEnum._values',
      []
    );
    return {
      immutableEvents: assembleResponse(baselineEvents, schemaEventNames),
      configurableEvents: assembleResponse(configuredEvents, schemaEventNames)
    };
  }

