async function helpGetGrantedPackage(client, input) {
  const { gqlClient, options } = client;
  const grantsQuery = `
    query getGrantPackage (
      $id: ID
      $orgId: ID
      $includeDeleted: Boolean = false
      $offset: Int
      $limit: Int
      $packageFilter: PackageGrantFilter
    ) {
      packageGrants(
        id: $id
        orgId: $orgId
        includeDeleted: $includeDeleted
        offset: $offset
        limit: $limit
        packageFilter: $packageFilter
      ) {
        records {
          package { id }
        }
      }
    }
  `;
  return gqlClient.query(grantsQuery, input, options);
}

async function helpUpdatePackageGrant(client, input) {
  const { gqlClient, options } = client;
  const { packageGrants, packageId } = input;

  let packageGrantString = '';
  if (!_.isEmpty(packageGrants)) {
    packageGrantString = packageGrants.reduce((query, record) => {
      query += `
        {
          organizationId: ${record.organizationId}
          action: ${record.action}
          grantType: ${record.grantType}
        },`;

      return query;
    }, ``);
  }

  const queryGrant = `
    mutation addGrant {
      packageUpdateGrants(
        input: {
          packageId: "${packageId}"
          packageGrants: [${packageGrantString}]
        }
      ) {
        id
        name
        version
      }
    }`;
  return gqlClient.query(queryGrant, {}, options);
}

